    async def get_notification_history(
        self,
        alert_type: str | None = None,
        alert_id: int | None = None,
        status: str | None = None,
        limit: int = 100,
        exclude_alert_types: list[str] | None = None,
    ) -> list[dict[str, Any]]:
        """Get notification history."""
        if self.db is None:
            return []

        if exclude_alert_types is None and alert_type is None:
            exclude_alert_types = ["checksum_report", "checksum_verification"]

        query = select(AlertNotificationHistory)
        if alert_type:
            query = query.where(AlertNotificationHistory.alert_type == alert_type)
        if alert_id:
            query = query.where(AlertNotificationHistory.alert_id == alert_id)
        if status:
            query = query.where(AlertNotificationHistory.status == status)
        if exclude_alert_types:
            query = query.where(AlertNotificationHistory.alert_type.notin_(exclude_alert_types))

        query = query.order_by(AlertNotificationHistory.sent_at.desc()).limit(limit)
        result = await self.db.execute(query)
        history = result.scalars().all()

        return [
            {
                "id": h.id,
                "sent_at": h.sent_at.isoformat(),
                "alert_type": h.alert_type,
                "notification_type": h.alert_type,
                "alert_id": h.alert_id,
                "recipient_email": h.recipient_email,
                "subject": h.subject or self._default_subject(h.alert_type),
                "status": h.status,
                "error_message": h.error_message,
            }
            for h in history
        ]
