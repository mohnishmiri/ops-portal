    async def send_checksum_comparison_report(
        self,
        recipient_email: str,
        system: str,  # attcc | ces
        workspace_name: str,
        run_id: str,
        total_pipelines: int,
        changed_count: int,
        added_count: int,
        removed_count: int,
        environment: str = "prod",
        comparison_link: str | None = None,
    ) -> bool:
        """
        Send Synapse checksum comparison report email.

        Args:
            recipient_email: Email recipient
            system: 'attcc' or 'ces'
            workspace_name: Synapse workspace name
            run_id: Checksum run ID
            total_pipelines: Total pipelines checked
            changed_count: Number of changed pipelines
            added_count: Number of added pipelines
            removed_count: Number of removed pipelines
            environment: Environment label
            comparison_link: URL to detailed report

        Returns:
            True if email sent successfully
        """
        try:
            status_emoji = "✅" if (changed_count + added_count + removed_count) == 0 else "⚠️"
            status_text = "No Changes" if (changed_count + added_count + removed_count) == 0 else "Changes Detected"

            subject = f"{status_emoji} Synapse Checksum Report: {system.upper()} - {workspace_name}"

            # HTML template
            html_content = self._render_checksum_html(
                system=system,
                workspace_name=workspace_name,
                run_id=run_id,
                total_pipelines=total_pipelines,
                changed_count=changed_count,
                added_count=added_count,
                removed_count=removed_count,
                environment=environment,
                status_text=status_text,
                status_emoji=status_emoji,
                comparison_link=comparison_link,
            )

            success = False
            send_results = await self._send_email_batch(
                recipient_emails=[recipient_email],
                subject=subject,
                html_body=html_content,
                alert_type="checksum_report",
                alert_id=0,
            )

            if send_results and send_results[0].get("status") == "sent":
                success = True
                logger.info(
                    "checksum_report_sent",
                    recipient=recipient_email,
                    system=system,
                    run_id=run_id,
                )
            return success

        except Exception as exc:
            logger.error(
                "checksum_report_send_failed",
                recipient=recipient_email,
                system=system,
                error=str(exc),
            )
            return False

